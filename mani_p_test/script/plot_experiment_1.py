#!/usr/bin/env python3
import pandas as pd
import matplotlib.pyplot as plt
import argparse
import sys
import numpy as np

def analyze_and_plot(csv_file):
    # 1. Load Data (Best Practice: Use Pandas)
    try:
        df = pd.read_csv(csv_file)
    except FileNotFoundError:
        print(f"Error: File '{csv_file}' not found.")
        return

    # Check columns
    required_cols = ['elapsed_time', 'frame_id', 'x', 'y', 'z', 'yaw']
    if not all(col in df.columns for col in required_cols):
        print(f"Error: CSV must contain columns: {required_cols}")
        return

    # 2. Separate Data by Frame ID
    # Assuming 'tag11' is Raw and 'shelf_filtered' is Filtered
    # We detect unique frame_ids dynamically
    frame_ids = df['frame_id'].unique()
    print(f"Found frames: {frame_ids}")

    # Setup Plotting (Best Practice: Use Subplots)
    fig, axes = plt.subplots(2, 2, figsize=(12, 8), sharex=True)
    fig.suptitle(f'Signal Processing Validation: {csv_file}', fontsize=16)

    # Colors for different frames
    colors = {'tag11': 'red', 'shelf_filtered': 'blue', 'raw': 'red', 'filtered': 'blue'}
    
    stats_summary = []

    for fid in frame_ids:
        subset = df[df['frame_id'] == fid]
        subset = subset.sort_values('elapsed_time')
        
        color = colors.get(fid, None) # Auto color if not in dict
        label = fid
        
        # Plot X
        axes[0, 0].plot(subset['elapsed_time'], subset['x'], label=label, color=color, alpha=0.7)
        axes[0, 0].set_title('Position X (m)')
        axes[0, 0].set_ylabel('X (m)')
        
        # Plot Y
        axes[0, 1].plot(subset['elapsed_time'], subset['y'], label=label, color=color, alpha=0.7)
        axes[0, 1].set_title('Position Y (m)')
        axes[0, 1].set_ylabel('Y (m)')
        
        # Plot Z
        axes[1, 0].plot(subset['elapsed_time'], subset['z'], label=label, color=color, alpha=0.7)
        axes[1, 0].set_title('Position Z (m)')
        axes[1, 0].set_ylabel('Z (m)')
        axes[1, 0].set_xlabel('Time (s)')

        # Plot Yaw
        axes[1, 1].plot(subset['elapsed_time'], subset['yaw'], label=label, color=color, alpha=0.7)
        axes[1, 1].set_title('Orientation Yaw (rad)')
        axes[1, 1].set_ylabel('Yaw (rad)')
        axes[1, 1].set_xlabel('Time (s)')

        # 3. Calculate Statistics (Best Practice: Vectorized operations)
        std_x = subset['x'].std()
        std_y = subset['y'].std()
        std_z = subset['z'].std()
        std_yaw = subset['yaw'].std()
        
        stats_summary.append({
            'Frame': fid,
            'SD_X': std_x,
            'SD_Y': std_y,
            'SD_Z': std_z,
            'SD_Yaw': std_yaw
        })

    # Add Legends
    for ax in axes.flat:
        ax.legend()
        ax.grid(True, linestyle='--', alpha=0.5)

    plt.tight_layout(rect=[0, 0.03, 1, 0.95]) # Make room for suptitle

    # 4. Print Statistics Table
    print("\n" + "="*60)
    print(f"{'Frame':<20} | {'SD X (mm)':<10} | {'SD Y (mm)':<10} | {'SD Z (mm)':<10} | {'SD Yaw (deg)':<10}")
    print("-" * 60)
    for stat in stats_summary:
        print(f"{stat['Frame']:<20} | {stat['SD_X']*1000:<10.4f} | {stat['SD_Y']*1000:<10.4f} | {stat['SD_Z']*1000:<10.4f} | {math.degrees(stat['SD_Yaw']):<10.4f}")
    print("="*60 + "\n")

    # Show Plot
    plt.show()

import math

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Plot Experiment 1 Results")
    parser.add_argument("csv_file", help="Path to the CSV file generated by tf_recorder.py")
    args = parser.parse_args()

    analyze_and_plot(args.csv_file)
